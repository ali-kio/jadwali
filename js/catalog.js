/* ----------------------------- قارئ الكتالوج ----------------------------- */
window.Catalog = (function () {
  const DEPTS = { CS: 'علوم الحاسوب', IS: 'نظم المعلومات', CE: 'هندسة الحاسوب' };
  const META = {
    year: '2026/2027',
    semester: 'الفصل الأول',
    college: 'كلية تقنية المعلومات',
    source: 'ucs.uob.edu.bh'
  };

  let courses = [];
  let index = {};

  function build() {
    const byCode = {};
    const aliases = [];
    let cur = null, sec = null;

    window.CATALOG_RAW.split('\n').forEach(line => {
      if (!line || line[0] === ' ') return;
      const p = line.split('|');

      if (p[0] === 'C') {
        cur = {
          code: p[1], title: p[2], dept: p[3],
          exam: p[4] ? { date: p[4], start: p[5], end: p[6] } : null,
          prereqs: p[7] || '',
          sections: []
        };
        byCode[cur.code] = cur;
        courses.push(cur);
        sec = null;
      } else if (p[0] === 'S' && cur) {
        sec = { section: p[1], instructor: p[2] || '', meetings: [] };
        cur.sections.push(sec);
      } else if (p[0] === 'M' && sec) {
        const kind = p[1] === 'B' ? 'lab' : 'lecture';
        String(p[2]).split('').forEach(d => {
          sec.meetings.push({ kind, day: +d, start: p[3], end: p[4], room: p[5] || '' });
        });
      } else if (p[0] === 'A') {
        aliases.push({ code: p[1], title: p[2], dept: p[3], from: p[4] });
      }
    });

    aliases.forEach(a => {
      const src = byCode[a.from];
      if (!src) return;
      const clone = {
        code: a.code, title: a.title, dept: a.dept,
        exam: src.exam, prereqs: src.prereqs, sameAs: src.code,
        sections: src.sections
      };
      byCode[a.code] = clone;
      courses.push(clone);
    });

    courses.sort((a, b) => a.code.localeCompare(b.code));
    courses.forEach(c => { c.deptName = DEPTS[c.dept] || c.dept; });
    index = byCode;
  }

  build();

  /** بحث بالرمز أو الاسم أو اسم المدرّس */
  function search(query, limit = 12) {
    const q = U.latinDigits(String(query || '')).trim().toUpperCase().replace(/\s+/g, ' ');
    if (!q) return [];
    const starts = [], has = [];
    courses.forEach(c => {
      const code = c.code.toUpperCase();
      const title = (c.title || '').toUpperCase();
      if (code.startsWith(q)) starts.push(c);
      else if (code.includes(q) || title.includes(q)) has.push(c);
      else if (c.sections.some(s => s.instructor.toUpperCase().includes(q))) has.push(c);
    });
    return starts.concat(has).slice(0, limit);
  }

  const get = code => index[String(code || '').trim().toUpperCase()] || null;
  const all = () => courses;
  const count = () => courses.length;

  /** يحوّل سكشن من الكتالوج إلى مقرر جاهز للحفظ */
  function toCourse(course, section, extra = {}) {
    const sessions = section.meetings.map(m => ({
      day: m.day, start: m.start, end: m.end,
      room: m.room, kind: m.kind, teacher: section.instructor
    }));
    const exams = [];
    if (course.exam && course.exam.date) {
      exams.push({
        kind: 'final', date: course.exam.date,
        start: course.exam.start, end: course.exam.end, room: ''
      });
    }
    return Object.assign({
      code: course.code,
      title: course.title,
      section: section.section,
      instructor: section.instructor,
      credits: 3,
      sessions, exams
    }, extra);
  }

  return { META, DEPTS, search, get, all, count, toCourse };
})();
